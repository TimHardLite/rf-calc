// Равномерная геометрическая теория дифракции (UTD) — дифракция на кромке экрана.
//
// ЗАЧЕМ. Классическая модель патч-антенны (Balanis) считает экран БЕСКОНЕЧНЫМ: тогда
// по теории изображений излучение существует только в верхней полусфере, а сзади строго
// ноль. У реальной антенны экран конечный, и за него заходит поле, продифрагировавшее
// на кромках. Именно это даёт заднее излучение −15…−20 дБ, которое видно на замерах.
//
// СЛУЧАЙ, КОТОРЫЙ НАМ НУЖЕН: излучающие щели патча лежат ПРЯМО НА экране, поэтому луч
// от щели к кромке идёт вдоль поверхности — это СКОЛЬЗЯЩЕЕ падение (φ' = 0), а кромка
// экрана — полуплоскость (клин с n = 2).
//
// Для n = 2 и φ' = 0 общая формула Kouyoumjian–Pathak резко упрощается. Четыре её члена
// попарно совпадают, поэтому:
//   • мягкая поляризация (E вдоль кромки):      D_мягк = 0
//   • жёсткая поляризация (E поперёк кромки):   D_жёстк = 2·C·{cot[(π+φ)/4] + cot[(π−φ)/4]}
// Далее используем тождество (проверяется численно в тестах):
//   cot[(π+φ)/4] + cot[(π−φ)/4] = 2/cos(φ/2)
// откуда окончательно
//   D(φ) = −e^{−jπ/4} / √(2πk) · F(X) / cos(φ/2),     X = 2·k·s'·cos²(φ/2)
// где s' — расстояние от источника до кромки, φ — угол наблюдения от освещённой грани,
// F — переходная функция Френеля (гасит особенность на границе тени).
//
// При скользящем падении к падающему полю дополнительно применяется множитель ½
// (классическое правило: падающее и отражённое поля сливаются).
//
// Источник методики: Kouyoumjian & Pathak, Proc. IEEE 62 (1974); изложение и применение
// к антеннам на экране конечного размера — Balanis, «Antenna Theory», гл. 13–14.

export interface Cx { re: number; im: number }

const cmul = (a: Cx, b: Cx): Cx => ({ re: a.re * b.re - a.im * b.im, im: a.re * b.im + a.im * b.re });
const cscale = (a: Cx, s: number): Cx => ({ re: a.re * s, im: a.im * s });
const cexp = (p: number): Cx => ({ re: Math.cos(p), im: Math.sin(p) });

/** Комплексный квадратный корень, главная ветвь. */
function csqrt(re: number, im: number): Cx {
  const r = Math.hypot(re, im);
  if (r < 1e-300) return { re: 0, im: 0 };
  const a = Math.sqrt((r + re) / 2);
  const b = Math.sign(im || 1) * Math.sqrt((r - re) / 2);
  return { re: a, im: b };
}

/**
 * Хвост интеграла Френеля  G(u) = ∫_u^∞ e^{−jτ²} dτ.
 * Поворотом контура (τ² = u² + t, затем t = −j·w²) приводится к быстро сходящемуся
 * интегралу с гауссовым весом, без особенности при u = 0:
 *   G(u) = −j·e^{−ju²} · ∫_0^∞ e^{−w²} · w / √(u² − j·w²) dw
 * Считаем составной формулой Симпсона: подынтегральная функция гладкая и затухает как e^{−w²}.
 */
function fresnelTail(u: number): Cx {
  const N = 600, W = 5.4, h = W / N;
  let sre = 0, sim = 0;
  for (let i = 0; i <= N; i++) {
    const w = i * h;
    const wt = i === 0 || i === N ? 1 : i % 2 ? 4 : 2;
    const den = csqrt(u * u, -w * w);
    const d2 = den.re * den.re + den.im * den.im;
    if (d2 < 1e-300) continue;
    const g = Math.exp(-w * w) * w;
    // g / den
    sre += (wt * g * den.re) / d2;
    sim += (wt * -g * den.im) / d2;
  }
  const k = h / 3;
  const I: Cx = { re: sre * k, im: sim * k };
  // −j · e^{−ju²} · I
  return cmul(cmul({ re: 0, im: -1 }, cexp(-u * u)), I);
}

/**
 * Переходная функция Френеля  F(X) = 2j√X · e^{jX} · ∫_√X^∞ e^{−jτ²} dτ.
 * Предельные значения: F(0) = 0, F(X→∞) = 1 — именно они гасят особенность
 * коэффициента дифракции на границе тени.
 */
export function fresnelTransition(X: number): Cx {
  if (X <= 0) return { re: 0, im: 0 };
  if (X < 0.05) {
    // Ряд малых аргументов. Нужен именно он: при X → 0 подынтегральная функция хвоста
    // Френеля меняется на масштабе √X, и равномерная сетка её не разрешает.
    // Порог 0.05 выбран по сшивке с численной ветвью: при 0.3 обрыв ряда на X² уже
    // даёт ~2% расхождения, при 0.05 ветви сходятся в пределах 1e−4.
    //   F(X) = [√(πX) − 2X·e^{jπ/4} − (2/3)X²·e^{−jπ/4}] · e^{j(π/4+X)}
    const e1 = cexp(Math.PI / 4), e2 = cexp(-Math.PI / 4);
    const br: Cx = {
      re: Math.sqrt(Math.PI * X) - 2 * X * e1.re - (2 / 3) * X * X * e2.re,
      im: -2 * X * e1.im - (2 / 3) * X * X * e2.im,
    };
    return cmul(br, cexp(Math.PI / 4 + X));
  }
  if (X > 12) {
    // Асимптотика: 1 + j/(2X) − 3/(4X²) − j·15/(8X³) + 75/(16X⁴)
    return {
      re: 1 - 3 / (4 * X * X) + 75 / (16 * X * X * X * X),
      im: 1 / (2 * X) - 15 / (8 * X * X * X),
    };
  }
  const u = Math.sqrt(X);
  const tail = fresnelTail(u);
  return cmul(cscale(cmul({ re: 0, im: 2 * u }, cexp(X)), 1), tail);
}

/**
 * Коэффициент дифракции полуплоскости при скользящем падении, жёсткая поляризация.
 * @param phiRad угол наблюдения от освещённой грани экрана, 0…2π
 * @param sPrime расстояние от источника до кромки (м)
 * @param k      волновое число (1/м)
 * Возвращает D (размерность √м) — множитель для падающего поля.
 */
export function grazingEdgeD(phiRad: number, sPrime: number, k: number): Cx {
  const c = Math.cos(phiRad / 2);
  const X = 2 * k * sPrime * c * c;

  // На границе тени (φ = π) c → 0 и F(X)/c имеет КОНЕЧНЫЙ предел:
  //   F(X) ≈ √(πX)·e^{jπ/4} = |c|·√(2πk s')·e^{jπ/4}  ⇒  F/c → ±√(2πk s')·e^{jπ/4}
  // Поэтому особенности нет, но вблизи неё считаем предел явно, чтобы не делить на ~0.
  let ratio: Cx;
  if (Math.abs(c) < 1e-7) {
    ratio = cscale(cexp(Math.PI / 4), Math.sqrt(2 * Math.PI * k * sPrime) * Math.sign(c || 1));
  } else {
    ratio = cscale(fresnelTransition(X), 1 / c);
  }
  // D = −e^{−jπ/4}/√(2πk) · F(X)/cos(φ/2)
  return cscale(cmul(cexp(-Math.PI / 4), ratio), -1 / Math.sqrt(2 * Math.PI * k));
}
