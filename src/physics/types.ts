// Единые типы данных для расчёта диаграмм направленности (ДН).

import type { SweepPoint } from "./sweep";
export type { SweepPoint };

export const C0 = 299_792_458; // скорость света, м/с

/** Одна точка ДН: угол в градусах и уровень в дБ (0 дБ = максимум). */
export interface PatternPoint {
  angleDeg: number;
  valueDb: number;
}

/** Одна плоскость сечения ДН. */
export interface PatternPlane {
  /** Подпись плоскости, напр. "E-плоскость" или "Азимут". */
  label: string;
  /** Точки сечения (обычно 0..360° или 0..180° для полусферы). */
  points: PatternPoint[];
  /** true — рисовать только верхнюю полусферу (антенны с экраном/землёй). */
  hemisphere?: boolean;
}

/** Числовые результаты расчёта, попадающие в блок-справку под ДН. */
export interface PatternMetrics {
  /** Частота, МГц. */
  freqMHz: number;
  /** Длина волны в свободном пространстве, мм. */
  lambdaMm: number;
  /** Максимальный КНД (директивность), дБи. null — расчёт недостоверен. */
  directivityDbi: number | null;
  /** Ширина главного лепестка по уровню −3 дБ (град), по опорной плоскости. */
  hpbwDeg: number | null;
  /** Уровень первого бокового лепестка, дБ (null — нет). */
  sllDb: number | null;
  /** Отношение вперёд/назад F/B строго на 180°, дБ (null — не применимо).
   *  Внимание: это глубина конкретного направления, она может попасть в случайный нуль. */
  frontToBackDb: number | null;
  /** Заднее излучение по сектору ±60° вокруг обратного направления, дБ — худший случай.
   *  Именно эта величина нормируется в ТУ/паспорте; численно устойчива. */
  rearSectorDb?: number | null;
  /** Входной импеданс, Ом (для проволочных антенн). */
  impedanceR?: number;
  impedanceX?: number;
  /** КСВ относительно 50 Ом. */
  swr50?: number;
  /** Сходимость модели (self-check NEC2): средний КНД по сфере, идеал = 1.000.
   *  Только для методов моментов. Отклонение >10% — признак грубой сегментации. */
  avgGain?: number;

  // ---- Паспортные характеристики (выводятся там, где считаются корректно) ----
  /**
   * Коэффициент усиления (КУ), дБи = КНД × КПД.
   *
   * ВАЖНО, КАК ЭТО ПОНИМАТЬ. Рассогласование с трактом сюда НЕ входит — таково
   * общепринятое определение КУ (IEEE Std 145-2013), и именно так его нормируют
   * в ТУ и паспортах. Потери на рассогласовании идут ОТДЕЛЬНОЙ метрикой
   * `mismatchDb`; их разность — «реализованное усиление» (realized gain).
   * Для проволочных антенн из хорошего проводника КПД ≈ 1, поэтому КУ = КНД.
   */
  gainDbi?: number | null;
  /** Из чего сложилось усиление: КПД по потерям (0…1). undefined — потери не учитывались. */
  efficiency?: number;
  /**
   * КИП раскрыва (коэффициент использования поверхности апертуры, 0…1) — только для
   * апертурных антенн (рупор). ЭТО НЕ КПД: потерь мощности здесь нет, КИП показывает,
   * какую долю от максимума 4πS/λ² даёт неравномерное и несинфазное поле в раскрыве.
   * КНД и КУ УЖЕ посчитаны с его учётом, второй раз его вычитать нельзя.
   */
  apertureEff?: number;
  /** Потери на рассогласовании с 50 Ом, дБ. */
  mismatchDb?: number;
  /** Волновое сопротивление тракта/структуры, Ом (напр. TE10 в волноводе рупора). */
  waveImpedance?: number;
  /** Полоса по критерию КСВ ≤ swrCriterion: границы и ширина, МГц. */
  bandLowMHz?: number;
  bandHighMHz?: number;
  swrCriterion?: number;
  /** Добротность резонанса (справочно; полоса теперь берётся из свипа). */
  qFactor?: number;
  /** Свип по частоте: КСВ(f), R(f), X(f) — таблица и график полосы (physics/sweep.ts). */
  sweep?: SweepPoint[];
  /** Частота минимума КСВ по свипу, МГц (может не совпадать с рабочей). */
  swrMinFreqMHz?: number;
  /** Минимальный КСВ в окне свипа. */
  swrMin?: number;
  /** Поляризация — текстом, для паспорта. */
  polarization?: string;
  /** Осевое отношение для круговой поляризации, дБ (null/undefined — не считается). */
  axialRatioDb?: number | null;
  /** Ширина ДН по −3 дБ раздельно по двум главным плоскостям, град. */
  hpbwEDeg?: number | null;
  hpbwHDeg?: number | null;
  /** Подписи этих плоскостей («E / H», «гор. / верт.»). */
  hpbwELabel?: string;
  hpbwHLabel?: string;
}

/** Полный результат расчёта одной антенны. */
export interface PatternResult {
  antennaKind: string;
  title: string;
  planes: PatternPlane[];
  metrics: PatternMetrics;
  /** Плоскость, по которой считались HPBW/F-B (индекс в planes). */
  referencePlaneIndex: number;
  /** Предупреждения/пометки (например, отсутствующие данные). */
  notes: string[];
}
