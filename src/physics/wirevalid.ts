// Проверка применимости проволочной модели (общая для всех проволочных антенн).
//
// С версии, где для близких пар сегментов используется ТОЧНОЕ ЯДРО ТРУБКИ (как в
// MININEC-3, см. mom3d.ts), прежнее ограничение тонкопроволочного ядра Δ ≥ 8a снято:
// точное ядро устойчиво при любом отношении длины сегмента к радиусу (проверено:
// диполь 0.5λ, a = 0.01λ, сетка до λ/480 — решение сходится монотонно, тогда как
// приведённое ядро при Δ < 2a разваливалось, как и NEC-2 без EK).
// Остаются физические пределы модели:
//   1) a ≲ 0.01λ — ток по окружности трубки считается равномерным; для толстых
//      проводников это приближение, и импеданс сильнее зависит от реальной геометрии
//      узла питания (торцы, зазор);
//   2) Δ ≤ 0.1λ — иначе кусочная аппроксимация тока грубая.

export interface WireGeom {
  /** Радиус проводника (эквивалентный для полоски), м. */
  radiusM: number;
  /** Наибольшая длина сегмента, м. */
  maxSegM: number;
  /** Подпись для сообщения («рефлектор», «вибратор», …). */
  label?: string;
}

/** Предупреждения о выходе за область применимости. Пустой массив = всё в норме. */
export function thinWireWarnings(wires: WireGeom[], lambdaM: number): string[] {
  const out: string[] = [];
  let thickest = 0, thickLabel = "";
  let coarsest = 0, coarseLabel = "";
  for (const w of wires) {
    if (!(w.radiusM > 0) || !(w.maxSegM > 0)) continue;
    const aRel = w.radiusM / lambdaM;
    if (aRel > thickest) { thickest = aRel; thickLabel = w.label ?? ""; }
    const dRel = w.maxSegM / lambdaM;
    if (dRel > coarsest) { coarsest = dRel; coarseLabel = w.label ?? ""; }
  }
  const where = (s: string) => (s ? ` (${s})` : "");
  if (thickest > 0.01) {
    out.push(
      `⚠ Толстый проводник: радиус ${thickest.toFixed(4)}λ${where(thickLabel)} больше 0.01λ. Решатель использует ` +
      `точное ядро трубки и остаётся устойчивым, но ток по окружности уже неравномерен, а импеданс заметно ` +
      `зависит от реальной геометрии узла питания и торцов. Форма ДН и КНД достоверны, импеданс — ориентировочный.`,
    );
  }
  if (coarsest > 0.1) {
    out.push(
      `⚠ Сегмент ${coarsest.toFixed(3)}λ${where(coarseLabel)} грубее рекомендованных 0.1λ — ` +
      `результат ориентировочный, увеличьте детализацию геометрии.`,
    );
  }
  return out;
}
