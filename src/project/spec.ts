// Генератор спецификации формата .irta из описаний полей реестра.
// Документ docs/ФОРМАТ-IRTA.md НЕ пишется руками: его выпускает команда
//   npm run irta-spec
// а тест проверяет, что он совпадает с программой. Добавили поле в registry.ts —
// тест упадёт, пока спецификацию не перевыпустят. Так файл и программа не расходятся.

import { ANTENNAS } from "../registry";
import { describeFields, type FieldInfo } from "./schema";
import { MAGIC, VERSION } from "./format";

const cell = (s: string) => s.replace(/\|/g, "\\|");

function row(f: FieldInfo): string {
  const def = f.kind === "elements" ? "список в [elements]" : String(f.default);
  const range =
    f.kind === "select"
      ? f.options!.map((o) => `\`${o.value}\` — ${o.label}`).join("; ")
      : f.kind === "elements"
        ? "строки `тип, длина, диаметр, позиция` (мм)"
        : `${f.min ?? "…"} … ${f.max ?? "…"}`;
  return `| \`${f.key}\` | ${cell(f.label)} | ${f.unit || "—"} | ${cell(def)} | ${cell(range)} | ${f.condition ? cell(f.condition) : "всегда"} |`;
}

export function buildIrtaSpec(): string {
  const L: string[] = [];
  L.push(
    `# Формат файла проекта .irta — версия ${VERSION}`,
    "",
    "> Документ сгенерирован из описаний полей программы (`npm run irta-spec`). Не править вручную:",
    "> при добавлении поля в программу перевыпустить командой, иначе не пройдёт тест.",
    "",
    "## Устройство файла",
    "",
    "```",
    `${MAGIC}/${VERSION}                  ← подпись и версия формата (файлы ${MAGIC}/1 тоже читаются)`,
    "name = Яги 180 МГц          ← имя проекта (весь текст после «=», можно «№», «;», «#»)",
    "type = yagi                 ← тип антенны (см. ниже)",
    "mode = analysis             ← в каком режиме открыть: analysis | synthesis",
    "note = …                    ← необязательная заметка",
    "",
    "[params]                    ← ВСЕ поля «Поверочного расчёта»",
    "ключ = значение",
    "[elements]                  ← только яги: тип, длина, диаметр, позиция (мм)",
    "reflector, 921, 8, 0",
    "",
    "[synthesis]                 ← ВСЕ поля «Проектирования» (у рупора/решётки/… — тоже есть)",
    "ключ = значение",
    "```",
    "",
    "## Правила",
    "",
    "1. Кодировка UTF-8, обычный текст. Пустые строки игнорируются; `#` или `;` — комментарий до конца строки (кроме строк `name` и `note`).",
    "2. Число распознаётся, только если значение — чистое число (`12`, `-40`, `0.22`, `1e3`); иначе это строка. Значения списков пишутся без кавычек, точно как в колонке «варианты» (регистр важен).",
    "3. Программа сохраняет ВСЕ поля обоих режимов, включая поля, скрытые при текущем выборе в списке (колонка «используется при»). Скрытое поле на расчёт не влияет, но его значение вернётся, если после открытия переключить вариант.",
    "4. При экспорте из «Поверочного расчёта» — `mode = analysis`, в `[params]` состояние формы поверочного расчёта, в `[synthesis]` — состояние формы проектирования.",
    "   При экспорте из «Проектирования» — `mode = synthesis`, в `[synthesis]` — заданные цели, в `[params]` — РАССЧИТАННЫЕ размеры (при открытии они сразу попадают в поверочный расчёт).",
    "5. При открытии: известные ключи берутся из файла; поля, которых в файле нет, получают значения по умолчанию, и программа ПЕРЕЧИСЛЯЕТ их в сообщении; неизвестные ключи (опечатки) пропускаются и тоже перечисляются. Значения вне диапазона не считаются молча — под диаграммой будет понятная ошибка.",
    "6. Совместимость: в файле `IRTANT/1` был один набор полей в `[params]` — поля режима, указанного в `mode`. Он так и читается. Старое значение GNSS `groundPlane = yes` теперь означает конечный экран Ø `screenDiaMm` (по умолчанию 285,3 мм).",
    "7. Ошибки разбора (чужой файл, неизвестная секция, неверная строка элемента) сообщаются с номером строки.",
    "",
    "## Поля по типам антенн",
    "",
  );
  for (const a of ANTENNAS) {
    L.push(`### \`${a.id}\` — ${a.name}`, "");
    const modes: [string, typeof a.analysis.fields | undefined][] = [
      ["Поверочный расчёт — секция `[params]`", a.analysis.fields],
      ["Проектирование — секция `[synthesis]`", a.synthesis?.fields],
    ];
    for (const [title, fields] of modes) {
      if (!fields) {
        L.push("Проектирования у этого типа нет — секции `[synthesis]` в файле не будет.", "");
        continue;
      }
      L.push(`**${title}**`, "", "| ключ | поле | ед. | по умолч. | допустимо / варианты | используется при |", "|---|---|---|---|---|---|");
      for (const f of describeFields(fields)) L.push(row(f));
      L.push("");
    }
  }
  L.push(
    "## Пример (яги, поверочный расчёт)",
    "",
    "```",
    `${MAGIC}/${VERSION}`,
    "name = Яги 180 МГц",
    "type = yagi",
    "mode = analysis",
    "[params]",
    "freqMHz = 180",
    "feedGapMm = 20",
    "mounting = through-insulated",
    "boomDiaMm = 20",
    "boomShape = square",
    "floorDb = -40",
    "[elements]",
    "reflector, 921, 8, 0",
    "driven, 819, 6, 304",
    "director, 734, 6, 445",
    "[synthesis]",
    "freqMHz = 180",
    "elementCount = 7",
    "elementDiaMm = 6",
    "feedGapMm = 20",
    "boomDiaMm = 20",
    "boomShape = square",
    "mounting = through-insulated",
    "floorDb = -40",
    "```",
    "",
  );
  return L.join("\n");
}
